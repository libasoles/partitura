import { test, expect } from '@playwright/test';

test('settings sample all intensities; sidebar places, edits, undoes and hides them independently', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/es/');
  await expect(page.locator('#scoreStage[aria-busy="true"]')).toHaveCount(0);
  await page.locator('#scoreSettingsToggle').click();
  const category = page.locator('[data-category="dynamics"]');
  await expect(category.locator('.score-settings-icon')).toHaveCount(10);
  await category.getByRole('checkbox').check();
  await page.screenshot({ path: 'test-results/dynamics-settings.png' });
  await page.keyboard.press('Escape');
  const button = page.locator('#scoreBarlines [data-dynamic="pp"]');
  await expect(button).toBeVisible();
  await button.click();
  await expect(button).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#scoreStage g.measure').first().scrollIntoViewIfNeeded();
  const staff = await page.locator('#scoreStage g.measure').first().locator(':scope > g.staff > path').nth(2).boundingBox();
  await page.mouse.click(staff.x + 200, staff.y);
  await expect.poll(() => page.evaluate(() => window.scoreEditor.score.dynamics)).toEqual({ 0: [{ at: 0, value: 'pp' }] });
  expect(await page.evaluate(() => window.scoreEditor.score.hairpins)).toBeUndefined();
  await expect(page.locator('#scoreStage g.dynam')).toHaveCount(1);
  await page.screenshot({ path: 'test-results/dynamics-sidebar.png' });
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.ScoreStore.flush());
  await page.reload();
  await expect(page.locator('#scoreStage[aria-busy="true"]')).toHaveCount(0);
  await page.locator('.score-dynamic-trigger').click();
  await page.locator('#scoreDynamicsPopup [data-dynamic="f"]').click();
  await expect.poll(() => page.evaluate(() => window.scoreEditor.score.dynamics[0][0].value)).toBe('f');
  await page.keyboard.press('ControlOrMeta+z');
  await expect.poll(() => page.evaluate(() => window.scoreEditor.score.dynamics[0][0].value)).toBe('pp');
  await page.locator('.score-dynamic-trigger').click();
  await page.locator('#scoreDynamicsPopup .score-dynamics-none').click();
  await expect(page.locator('#scoreStage g.dynam')).toHaveCount(0);
  await page.locator('#scoreSettingsToggle').click();
  await category.getByRole('checkbox').uncheck();
  await page.keyboard.press('Escape');
  await expect(button).toBeHidden();
});

test('sidebar tools do not move the add-row button and intensities form one column', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/es/?banner=hide');
  await expect(page.locator('#scoreStage[aria-busy="true"]')).toHaveCount(0);
  await page.locator('#scoreSettingsToggle').click();
  const popup = page.locator('#scoreSettingsPopup');
  await popup.getByRole('group', { name: 'Instrumento' }).locator('label').filter({ hasText: 'Guitarra' }).click();
  await popup.getByRole('checkbox', { name: 'Repetición', exact: true }).uncheck();
  await popup.getByRole('checkbox', { name: 'Dinámica', exact: true }).uncheck();
  const position = () => page.locator('#scoreAddRow').evaluate((el) => el.getBoundingClientRect().top + window.scrollY);
  const before = await position();
  await popup.getByRole('checkbox', { name: 'Dinámica', exact: true }).check();
  expect(Math.abs(await position() - before)).toBeLessThan(1);
  await popup.getByRole('checkbox', { name: 'Repetición', exact: true }).check();
  expect(Math.abs(await position() - before)).toBeLessThan(1);
  await page.keyboard.press('Escape');
  const boxes = await page.locator('.score-intensities button').evaluateAll((buttons) => buttons.map((el) => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y }; }));
  expect(new Set(boxes.map((box) => box.x)).size).toBe(1);
  expect(boxes.every((box, i) => !i || box.y > boxes[i - 1].y)).toBe(true);
});
